def corpus_table_html(stem, meta):
    df = pd.read_csv(CORPUS / 'tables' / f'{stem}.csv', dtype=str, keep_default_na=False)
    title = meta.get('title', stem); note = meta.get('note', '')
    table = df.to_html(index=False, escape=True, border=0, classes='table table-striped table-sm')
    return (f'<details class="corpus-table"><summary><b>{escape(title)}</b> <span class="muted">({stem}.csv; {len(df)} rows)</span></summary>'
            f'<div class="analysis-table" role="region" tabindex="0">{table}</div>'
            + (f'<p class="table-note">{escape(note)}</p>' if note else '') + '</details>')


def corpus_index():
    """Order and thematic groups of the module-17 index (`extended_material_index.md`, written in Spanish);
    identifiers and group names are returned in English."""
    rows = {'article_figures': [], 'article_tables': [], 'figures': [], 'tables': []}
    for line in (CORPUS / 'extended_material_index.md').read_text(encoding='utf-8').splitlines():
        if not line.startswith('| '):
            continue
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        m = re.match(r'(Figura|Tabla) (S?\d+)$', cells[0])
        if not m:
            continue
        kind = m.group(1)
        ident = ('Figure ' if kind == 'Figura' else 'Table ') + m.group(2)
        if len(cells) == 3:
            rows['article_figures' if kind == 'Figura' else 'article_tables'].append(
                {'id': ident, 'file': cells[1].strip('`'), 'desc': cells[2]})
        elif len(cells) == 5:
            rows['figures' if kind == 'Figura' else 'tables'].append(
                {'id': ident, 'group': GROUP_LABELS.get(cells[1], cells[1]), 'file': cells[2].strip('`'), 'origin': cells[3], 'desc': cells[4]})
    return rows


def corpus_lookup(stem, main, extra, fallback_id, fallback_desc, key='title'):
    meta = main.get(stem) or extra.get(stem) or {}
    if not meta.get(key):
        meta = dict(meta); meta[key] = f'{fallback_id}. {fallback_desc}'
    return meta


# ------------------------------------------------------------------ version registry
# `versions.json` records what each manuscript version added to the results. Its counts come from
# `scripts/audit_versions.py`, which hashes every tidy table, so the pages below cannot drift from
# the audit: they are rendered from the registry rather than written by hand.
REGISTRY = json.loads((HERE / 'versions.json').read_text(encoding='utf-8'))


def versions():
    """Every version of the series, in chronological order."""
    return REGISTRY['versions']


def version(vid):
    """One version by its two-digit id."""
    return next(v for v in REGISTRY['versions'] if v['id'] == vid)


def audit_note():
    """The finding of the table-level audit, for pages that need to state it."""
    return REGISTRY['audit']['finding']


def version_rows_html():
    """The index table: one row per version, saying what it added and where its results are."""
    head = ('<thead><tr><th>Version</th><th>Date</th><th>What it is</th>'
            '<th>Tidy tables</th><th>Results</th></tr></thead>')
    rows = []
    for v in versions():
        same = v.get('identical_results_to')
        tables = str(v['tidy_tables']) if v['tidy_tables'] else '—'
        if same:
            tables += f' <span class="same-as">= v{same}</span>'
        name = f"v{v['id']} · {escape(v['title'])}"
        link = f'<a href="{v["page"]}">{name}</a>' if v.get('page') else name
        rows.append(f'<tr><td>{link}</td><td>{v["date"]}</td><td>{escape(v["what"])}</td>'
                    f'<td class="num">{tables}</td><td>{escape(v["results"])}</td></tr>')
    return f'<table class="version-index">{head}<tbody>{"".join(rows)}</tbody></table>'


def figure_files(stem, lang='en'):
    """Links to the exported formats of one plate, skipping formats that were not produced."""
    out = []
    for ext in ('png', 'svg', 'pdf'):
        if (HERE / 'figures' / lang / f'{stem}.{ext}').exists():
            out.append(f'[{ext.upper()}]({REL}/figures/{lang}/{stem}.{ext})')
    return ' · '.join(out)


def data_tables():
    """The public tidy tables the site ships, with their size, so a page can list what it reproduces from."""
    out = []
    for p in sorted((HERE / 'data').glob('*.csv')):
        with p.open(encoding='utf-8', errors='replace') as fh:
            rows = sum(1 for _ in fh) - 1
        out.append({'name': p.name, 'rows': max(rows, 0), 'kb': round(p.stat().st_size / 1024, 1)})
    return out
