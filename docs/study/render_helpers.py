"""Presentation helpers for the docs/ pages that reproduce the study manuscript (version 10) and the extended
corpus of the pipeline.

`contenido_v10.json` is written by `export_docs_content.py` (revision 10), which runs the real document builder
with its writing methods intercepted: resolved text with numbered citations, tables, legends, equations and
references, in English and Spanish. The plates are generated by `figuras_principales.py` and
`figuras_suplementarias.py` from `data/`; this module only presents them.
"""
from pathlib import Path
from html import escape
import json
import re
import pandas as pd
from PIL import Image

HERE = Path(__file__).resolve().parent            # docs/study
REL = 'study'                                      # relative path from docs/*.qmd
CONTENT = json.loads((HERE / 'data' / 'contenido_v10.json').read_text(encoding='utf-8'))
LABELS = {
    'en': {'files': 'Plate files (175 mm, {dpi}): ', 'dpi': '300 dpi', 'dpi_static': '300 dpi, revision 09', 'eq': 'Eq. ', 'rows': 'rows'},
    'es': {'files': 'Archivos de la lámina (175 mm, {dpi}): ', 'dpi': '300 ppp', 'dpi_static': '300 ppp, revisión 09', 'eq': 'Ec. ', 'rows': 'filas'},
}


def events(doc, lang='en'):
    return CONTENT[lang][doc]


def html_table(title, columns, rows, kinds, notes, small=True):
    cls = 'table table-striped table-sm' if small else 'table table-striped'
    out = [f'<div class="analysis-table" role="region" tabindex="0"><table class="{cls}">',
           f'<caption>{title}</caption>', '<thead><tr>' + ''.join(f'<th>{escape(c)}</th>' for c in columns) + '</tr></thead><tbody>']
    for r, k in zip(rows, kinds):
        if k == 'group':
            out.append(f'<tr class="table-group"><td colspan="{len(columns)}"><b>{escape(r[0])}</b></td></tr>')
        else:
            out.append('<tr>' + ''.join(f'<td>{escape(str(v))}</td>' for v in r) + '</tr>')
    out.append('</tbody></table>')
    if notes:
        out.append(f'<p class="table-note">{notes}</p>')
    out.append('</div>')
    return '\n'.join(out)


def figure_md(fig_id, lang, title, caption):
    preview = f'{REL}/qa/Figure_{fig_id}_{lang}_preview.png'
    exts = ('png', 'pdf') if fig_id in ('S1', 'S6') else ('png', 'svg', 'pdf')     # S1 and S6: inherited plates without SVG
    links = ' · '.join(f'[{ext.upper()}]({REL}/figures/{lang}/Figure_{fig_id}.{ext})' for ext in exts)
    cap = f'**{escape(title)}** {escape(caption)}'
    lab = LABELS[lang]
    files = lab['files'].format(dpi=lab['dpi'] if fig_id not in ('S1', 'S6') else lab['dpi_static'])
    return (f'![{cap}]({preview}){{fig-align="center" width="100%"}}\n\n'
            f'<p class="fig-links">{files}{links}</p>')


def equation_html(e, lang):
    imgs = []
    for rel in e['images']:
        with Image.open(HERE / rel) as im:
            w = round(im.width / 600 * 96 * 10 / 15)      # composed at 15 pt and 600 dpi, printed at 10 pt
        imgs.append(f'<img src="{REL}/{rel}" width="{w}" alt="{escape(e["label"])}">')
    num = LABELS[lang]['eq'] + str(e['number'])
    return (f'<div class="equation"><div class="eq-label">{escape(e["label"])}</div>'
            f'<div class="eq-row"><div class="eq-body">{"<br>".join(imgs)}</div><div class="eq-num">{num}</div></div></div>')


def render(doc, lang='en', skip_title=True, heading_shift=1):
    """Markdown (with embedded HTML) of the exported document, in the order of the DOCX."""
    out = []
    for e in events(doc, lang):
        k = e['kind']
        if k == 'title':
            if not skip_title:
                out.append('## ' + e['html'])
        elif k in ('h1', 'h2', 'h3'):
            level = int(k[1]) + heading_shift
            out.append('#' * level + ' ' + e['html'])
        elif k == 'p':
            out.append(e['html'])
        elif k == 'ric_start':
            out.append('::: {.research-context}')
        elif k == 'ric_end':
            out.append(':::')
        elif k == 'table':
            out.append(html_table(e['title'], e['columns'], e['rows'], e['kinds'], e['notes']))
        elif k == 'figure':
            out.append(figure_md(e['id'], lang, e['title'], e['caption']))
        elif k == 'equation':
            out.append(equation_html(e, lang))
        elif k == 'references':
            out.append('#' * (1 + heading_shift) + ' ' + e['title'])
            out.append('\n'.join(f'{it["n"]}. {escape(it["text"])}' for it in e['items']))
    return '\n\n'.join(out)


def summary_counts(doc, lang='en'):
    ev = events(doc, lang)
    return {'paragraphs': sum(e['kind'] == 'p' for e in ev), 'tables': sum(e['kind'] == 'table' for e in ev),
            'figures': sum(e['kind'] == 'figure' for e in ev), 'equations': sum(e['kind'] == 'equation' for e in ev),
            'references': sum(len(e['items']) for e in ev if e['kind'] == 'references')}


